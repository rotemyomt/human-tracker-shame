// Builds web/index.html as ONE self-contained file (inline CSS, inline scripts, built-in sound as a
// data URI), so it works when opened directly by double-click (file://), where Chrome blocks loading
// separate module files. Source: web/src.html + web/css/styles.css + web/js/*.js + web/media/presence.mp4
//   Run:  node tools/build-standalone.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const web = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'web');
const order = ['settings', 'mapping', 'stateMachine', 'serial', 'servo', 'camera', 'detector', 'tracker', 'audio', 'overlay', 'scene', 'main'];
let js = '';
for (const m of order) {
  let src = fs.readFileSync(path.join(web, 'js', `${m}.js`), 'utf8');
  src = src.replace(/^import[\s\S]*?from\s+['"][^'"]+['"];\s*$/gm, '');
  src = src.replace(/^export\s+\{[^}]*\};?\s*$/gm, '');
  const names = [...src.matchAll(/^export\s+(?:async\s+)?(?:const|let|class|function)\s+([A-Za-z_$][\w$]*)/gm)].map(x => x[1]);
  src = src.replace(/^export\s+(?=(const|let|class|function|async))/gm, '');
  // Each module gets its own scope; only its exports become visible to later modules.
  js += m === 'main'
    ? `\n// ===== ${m}.js =====\n{\n${src}\n}\n`
    : `\n// ===== ${m}.js =====\nconst { ${names.join(', ')} } = (() => {\n${src}\nreturn { ${names.join(', ')} };\n})();\n`;
}
const css = fs.readFileSync(path.join(web, 'css', 'styles.css'), 'utf8');
const media = path.join(web, 'media', 'presence.mp4');
const sound = fs.existsSync(media) ? `<script>window.HT_BUILTIN_SOUND = "data:audio/mp4;base64,${fs.readFileSync(media).toString('base64')}";</script>\n` : '';
let html = fs.readFileSync(path.join(web, 'src.html'), 'utf8');
html = html.replace('<link rel="stylesheet" href="css/styles.css" />', () => `<style>\n${css}\n</style>`);
html = html.replace('<script type="module" src="js/main.js"></script>', () => `${sound}<script type="module">\n${js}\n</script>`);
fs.writeFileSync(path.join(web, 'index.html'), `<!-- GENERATED by tools/build-standalone.mjs — edit web/src.html, web/css and web/js instead -->\n${html}`);
console.log('wrote web/index.html', html.length, 'bytes');
